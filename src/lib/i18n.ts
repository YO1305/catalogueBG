const dictionaries: Record<Lang, Record<string, string>> = { ru, en, uz };

export function translate(lang: Lang, key: string, vars?: Record<string, string | number>) {
  let text = dictionaries[lang][key] ?? dictionaries.ru[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function statusKey(status: string) {
  if (status === "published") return "common.published";
  if (status === "live") return "common.live";
  if (status === "archived") return "common.archived";
  if (status === "in_work") return "leads.statusWork";
  if (status === "done") return "leads.statusDone";
  if (status === "new") return "leads.statusNew";
  return "common.draft";
}

